export function createI18n(storage) {
  let language = 'en';
  try {
    const saved = storage?.getItem('kando-language');
    if (Object.hasOwn(messages, saved)) language = saved;
  } catch {}
  return {
    get language() { return language; },
    get locale() { return language === 'de' ? 'de-DE' : 'en-US'; },
    setLanguage(value) {
      language = Object.hasOwn(messages, value) ? value : 'en';
      try { storage?.setItem('kando-language', language); } catch {}
    },
    t(key, values = {}) {
      const template = messages[language][key] ?? messages.en[key] ?? key;
      return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
    },
  };
}

export function translatePage(root, i18n) {
  for (const attribute of ['text', 'aria-label', 'placeholder', 'content']) {
    const name = attribute === 'text' ? 'data-i18n' : `data-i18n-${attribute}`;
    root.querySelectorAll(`[${name}]`).forEach((element) => {
      const text = i18n.t(element.getAttribute(name));
      if (attribute === 'text') element.textContent = text;
      else element.setAttribute(attribute, text);
    });
  }
  root.documentElement.lang = i18n.language;
}
